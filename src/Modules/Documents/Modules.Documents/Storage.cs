using System.Buffers.Binary;
using System.Net.Sockets;
using System.Text;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Modules.Documents.Contracts;
using Shared.Infrastructure;

namespace Modules.Documents;

/// <summary>Private file storage (security.md §4): uploads land in quarantine and move to clean after the scan.</summary>
public interface IDocumentStore
{
    Task PutQuarantinedAsync(string key, Stream content, CancellationToken cancellationToken);

    Task ReleaseAsync(string key, CancellationToken cancellationToken);

    Task<Stream> OpenCleanAsync(string key, CancellationToken cancellationToken);

    /// <summary>The quarantined blobs created before <paramref name="before"/> (task 020 orphan cleanup).</summary>
    IAsyncEnumerable<string> QuarantinedBeforeAsync(DateTimeOffset before, CancellationToken cancellationToken);

    Task DeleteQuarantinedAsync(string key, CancellationToken cancellationToken);
}

/// <summary>Scans a file before it can be downloaded (task 006). Returns Clean, Infected or Pending (no verdict yet).</summary>
public interface IMalwareScanner
{
    Task<ScanStatus> ScanAsync(Stream content, CancellationToken cancellationToken);
}

/// <summary>
/// Documents on the server's disk (ADR-023): <c>{Storage:Root}/documents/quarantine</c> until the scan says clean, then
/// <c>/clean</c>. Keys are random hex names generated by <see cref="DocumentService"/>; files are never served directly.
/// </summary>
internal sealed class FileSystemDocumentStore(IConfiguration configuration, IHostEnvironment environment) : IDocumentStore
{
    public const string QuarantineArea = "documents/quarantine";

    public const string CleanArea = "documents/clean";

    private readonly string _root = FileStorage.Root(configuration, environment);

    public async Task PutQuarantinedAsync(string key, Stream content, CancellationToken cancellationToken)
    {
        var path = FileStorage.PathFor(_root, QuarantineArea, key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None);
        await content.CopyToAsync(file, cancellationToken);
    }

    public Task ReleaseAsync(string key, CancellationToken cancellationToken)
    {
        var target = FileStorage.PathFor(_root, CleanArea, key);
        Directory.CreateDirectory(Path.GetDirectoryName(target)!);
        File.Move(FileStorage.PathFor(_root, QuarantineArea, key), target);
        return Task.CompletedTask;
    }

    public Task<Stream> OpenCleanAsync(string key, CancellationToken cancellationToken) =>
        Task.FromResult<Stream>(new FileStream(FileStorage.PathFor(_root, CleanArea, key), FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true));

    public async IAsyncEnumerable<string> QuarantinedBeforeAsync(DateTimeOffset before, [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken)
    {
        var folder = Path.Combine(_root, QuarantineArea);
        if (!Directory.Exists(folder))
        {
            yield break;
        }

        foreach (var file in Directory.EnumerateFiles(folder, "*", SearchOption.AllDirectories))
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (File.GetCreationTimeUtc(file) < before.UtcDateTime)
            {
                yield return Path.GetRelativePath(folder, file).Replace(Path.DirectorySeparatorChar, '/');
            }
        }

        await Task.CompletedTask;
    }

    public Task DeleteQuarantinedAsync(string key, CancellationToken cancellationToken)
    {
        File.Delete(FileStorage.PathFor(_root, QuarantineArea, key));
        return Task.CompletedTask;
    }
}

/// <summary>
/// Local and test scanner (configuration <c>Documents:Scanner = Fake</c>): a file containing the EICAR test string is
/// infected. On the server <see cref="ClamAvScanner"/> scans (ADR-023).
/// </summary>
internal sealed class FakeMalwareScanner : IMalwareScanner
{
    private static readonly byte[] Eicar = Encoding.ASCII.GetBytes("EICAR-STANDARD-ANTIVIRUS-TEST-FILE");

    public async Task<ScanStatus> ScanAsync(Stream content, CancellationToken cancellationToken)
    {
        using var buffer = new MemoryStream();
        await content.CopyToAsync(buffer, cancellationToken);
        return buffer.GetBuffer().AsSpan(0, (int)buffer.Length).IndexOf(Eicar) >= 0 ? ScanStatus.Infected : ScanStatus.Clean;
    }
}

/// <summary>
/// ClamAV (<c>clamd</c>) over TCP with the INSTREAM command (ADR-023; <c>Documents:Scanner = ClamAV</c>): "OK" is clean,
/// "FOUND" is infected. No answer, an error or a timeout gives no verdict, so the file stays Pending in quarantine and
/// cannot be downloaded (fail closed); the user uploads it again once the scanner is back.
/// </summary>
internal sealed partial class ClamAvScanner(string host, int port, ILogger<ClamAvScanner> logger) : IMalwareScanner
{
    private const int ChunkSize = 64 * 1024;

    private static readonly TimeSpan Timeout = TimeSpan.FromSeconds(60);

    public async Task<ScanStatus> ScanAsync(Stream content, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);
        using var timeout = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
        timeout.CancelAfter(Timeout);
        try
        {
            using var client = new TcpClient();
            await client.ConnectAsync(host, port, timeout.Token);
            await using var stream = client.GetStream();
            await stream.WriteAsync("zINSTREAM\0"u8.ToArray(), timeout.Token);
            var buffer = new byte[ChunkSize];
            var length = new byte[4];
            int read;
            while ((read = await content.ReadAsync(buffer, timeout.Token)) > 0)
            {
                BinaryPrimitives.WriteInt32BigEndian(length, read);
                await stream.WriteAsync(length, timeout.Token);
                await stream.WriteAsync(buffer.AsMemory(0, read), timeout.Token);
            }

            BinaryPrimitives.WriteInt32BigEndian(length, 0);
            await stream.WriteAsync(length, timeout.Token);
            using var reader = new StreamReader(stream, Encoding.ASCII);
            var reply = (await reader.ReadToEndAsync(timeout.Token)).TrimEnd('\0', '\n');
            if (reply.EndsWith("OK", StringComparison.Ordinal))
            {
                return ScanStatus.Clean;
            }

            if (reply.EndsWith("FOUND", StringComparison.Ordinal))
            {
                return ScanStatus.Infected;
            }

            LogNoVerdict(logger, reply.Length > 120 ? reply[..120] : reply);
            return ScanStatus.Pending;
        }
        catch (Exception exception) when (exception is SocketException or IOException || (exception is OperationCanceledException && !cancellationToken.IsCancellationRequested))
        {
            LogUnavailable(logger, exception.GetType().Name);
            return ScanStatus.Pending;
        }
    }

    [LoggerMessage(Level = LogLevel.Warning, Message = "ClamAV gave no verdict: {Reply}")]
    private static partial void LogNoVerdict(ILogger logger, string reply);

    [LoggerMessage(Level = LogLevel.Error, Message = "ClamAV is not reachable ({Error}); the upload stays quarantined.")]
    private static partial void LogUnavailable(ILogger logger, string error);
}

/// <summary>
/// The scanner when none is configured outside local development: it gives no verdict, so every upload stays Pending in
/// quarantine and cannot be downloaded (fail closed).
/// </summary>
internal sealed class DeferredMalwareScanner : IMalwareScanner
{
    public Task<ScanStatus> ScanAsync(Stream content, CancellationToken cancellationToken) => Task.FromResult(ScanStatus.Pending);
}
